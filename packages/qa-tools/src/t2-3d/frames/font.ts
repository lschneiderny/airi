const BOX = [0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F]

export const GLYPH_WIDTH = 6
export const GLYPH_HEIGHT = 8

/** Draws `text` into an RGB buffer with its top-left corner at (x, y), each font pixel `scale` image pixels wide. */
export function drawText(rgb: Uint8Array, width: number, height: number, x: number, y: number, text: string, scale = 1, color: readonly [number, number, number] = [20, 20, 20]): void {
  for (const [n, char] of [...text.toLowerCase()].entries()) {
    const rows = GLYPHS[char] ?? BOX
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if (!(rows[row] & (0x10 >> col)))
          continue
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            const px = x + (n * GLYPH_WIDTH + col) * scale + dx
            const py = y + row * scale + dy
            if (px >= 0 && px < width && py >= 0 && py < height)
              rgb.set(color, (py * width + px) * 3)
          }
        }
      }
    }
  }
}
