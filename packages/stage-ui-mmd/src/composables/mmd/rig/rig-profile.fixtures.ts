import type { MMDRigSource } from './rig-profile'

// Literals copied from the PMX audit (three-mmd 0.2.0-beta.2 PmxReader): post-parse positions
// and IK limits, as in `mmd.pmx`. Each fixture keeps the humanoid and control bones with their
// ancestors, their rigid bodies, and two mode-1 and two mode-2 bodies from elsewhere.

export type Vec3Tuple = [number, number, number]

export interface RigFixtureBone {
  name: string
  parent: string | null
  position: Vec3Tuple
  ik?: {
    target: string
    iteration: number
    rotationConstraint: number
    links: { bone: string, min?: Vec3Tuple, max?: Vec3Tuple }[]
  }
}

export interface RigFixture {
  bones: RigFixtureBone[]
  rigidBodies: { name: string, bone: string, physicsMode: 0 | 1 | 2 }[]
}

/** Resolves the name references of a fixture into the index-based PMX shape `mmd.pmx` uses. */
export function toPmxRigSource(fixture: RigFixture): MMDRigSource {
  const indexOf = (name: string): number => {
    const index = fixture.bones.findIndex(bone => bone.name === name)
    if (index < 0)
      throw new Error(`fixture references unknown bone ${name}`)
    return index
  }
  return {
    bones: fixture.bones.map(bone => ({
      name: bone.name,
      position: bone.position,
      parentBoneIndex: bone.parent === null ? -1 : indexOf(bone.parent),
      ik: bone.ik && {
        target: indexOf(bone.ik.target),
        iteration: bone.ik.iteration,
        rotationConstraint: bone.ik.rotationConstraint,
        links: bone.ik.links.map(link => ({
          target: indexOf(link.bone),
          limitation: link.min && link.max ? { minimumAngle: link.min, maximumAngle: link.max } : undefined,
        })),
      },
    })),
    rigidBodies: fixture.rigidBodies.map(body => ({
      name: body.name,
      boneIndex: indexOf(body.bone),
      physicsMode: body.physicsMode,
    })),
  }
}

