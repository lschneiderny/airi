import type { PmxMorphInfo } from './derive'

/** [name, PMX panel, PMX type] rows copied from the 2026-10-31 PMX audit (`pmx-audit/audit.json`); indices are row positions. */
export type MorphRow = readonly [name: string, category: number, type: number]

export function morphInfos(rows: readonly MorphRow[]): PmxMorphInfo[] {
  return rows.map(([name, category, type], index) => ({ index, name, category, type }))
}

